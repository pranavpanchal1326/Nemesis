"""The developer portal, bulk export, and version discovery.

**The reference is generated, never written.** FastAPI already produces an
OpenAPI document from the code, and this serves a rendered view of it. A
hand-written reference is a second description of the same contract, and the two
diverge on the first change nobody remembered to mirror — at which point the
documentation is worse than none, because a consumer trusts it.

**The portal is served as HTML from this process rather than as a static site.**
There is no CDN, no build step, and no separate deployment to keep in sync; the
page a consumer reads is generated by the same build that serves the API, so it
cannot describe a version this deployment does not run. The page has no external
assets at all — a public accountability surface that fetches a font from a third
party leaks every reader's address to that third party.

**The sandbox is a real tenant with synthetic data.** Not a mocked response
path: a mock proves the shape and nothing about whether the query works, and the
integration that passes against a mock is the one that fails on first contact
with suppression, pagination, and empty buckets. The sandbox is provisioned
through the ordinary control plane and its data is generated, so an integrator
exercises the real code against rows no citizen submitted.
"""

from __future__ import annotations

import html
from datetime import UTC, datetime
from typing import Annotated, Final

from fastapi import APIRouter, Query, Request, Response
from fastapi.responses import HTMLResponse, StreamingResponse
from pydantic import BaseModel, ConfigDict

from nemesis.api.deps import ConfigDep, SessionDep
from nemesis.api.errors import HTTP_422_UNPROCESSABLE, PROBLEM_BASE, ProblemDetailError
from nemesis.api.key_deps import KeyDep
from nemesis.api.versioning import (
    PUBLIC_API_NOTICE_DAYS,
    all_versions,
    current_version,
    sunset_notice_remaining,
)
from nemesis.integrations import keys, webhooks
from nemesis.public import export

#: Versioned endpoints — discovery and export live under /api/v1 like everything
#: else, because both are contracts a consumer integrates against.
router = APIRouter(tags=["developers"])

#: The portal itself is mounted at the *root*, unversioned. It is a page for a
#: human, not a contract for a client, and the ``Link rel="deprecation"`` header
#: on a sunset v1 response has to point somewhere that outlives v1 — a
#: deprecation notice hosted inside the deprecated version is a note left in the
#: building being demolished.
portal_router = APIRouter(tags=["developers"], include_in_schema=False)


class ApiModel(BaseModel):
    model_config = ConfigDict(frozen=True)


class VersionResponse(ApiModel):
    name: str
    status: str
    released_on: str
    deprecated_on: str | None
    sunset_on: str | None
    successor: str | None
    days_until_sunset: int | None
    description: str


class VersionsResponse(ApiModel):
    current: str
    notice_period_days: int
    policy: str
    versions: list[VersionResponse]


@router.get("/versions", summary="Published API versions and their deprecation clock")
async def versions() -> VersionsResponse:
    """Machine-readable version discovery.

    A consumer that polls this can warn its own operators months before a sunset
    without anybody reading a changelog — which is the difference between a
    published clock and an announced one.
    """
    today = datetime.now(tz=UTC).date()
    return VersionsResponse(
        current=current_version().name,
        notice_period_days=PUBLIC_API_NOTICE_DAYS,
        policy=(
            f"A published API version is removed no sooner than {PUBLIC_API_NOTICE_DAYS} days "
            f"after its deprecation is announced. Deprecation and removal dates are carried "
            f"on every response as RFC 9745 'Deprecation' and RFC 8594 'Sunset' headers."
        ),
        versions=[
            VersionResponse(
                name=version.name,
                status=str(version.status),
                released_on=version.released_on.isoformat(),
                deprecated_on=(
                    None if version.deprecated_on is None else version.deprecated_on.isoformat()
                ),
                sunset_on=None if version.sunset_on is None else version.sunset_on.isoformat(),
                successor=version.successor,
                days_until_sunset=sunset_notice_remaining(version, today),
                description=version.description,
            )
            for version in all_versions()
        ],
    )


# ---------------------------------------------------------------------------
# Bulk export
# ---------------------------------------------------------------------------

_DATASETS: Final = {
    "complaints": export.COMPLAINT_COLUMNS,
    "work-orders": export.WORK_ORDER_COLUMNS,
}


@router.get(
    "/export/{dataset}",
    summary="Bulk extract for RTI applicants and researchers",
    response_class=StreamingResponse,
)
async def bulk_export(
    dataset: str,
    caller: KeyDep,
    session: SessionDep,
    settings: ConfigDep,
    fmt: Annotated[str, Query(alias="format")] = "csv",
    since: Annotated[datetime | None, Query()] = None,
    until: Annotated[datetime | None, Query()] = None,
) -> StreamingResponse:
    """Streamed CSV or NDJSON, scoped to the calling key's tenant.

    **Requires a key**, unlike the aggregate endpoints. Not because the rows are
    more sensitive — they go through the same scrub — but because a full-scan
    extract is a fundamentally different cost from a cached aggregate, and an
    unauthenticated full scan is a denial-of-service primitive anyone can fire.
    Issuing a key to a researcher is a conversation that takes a minute and gives
    them a quota; leaving it open gives everybody an unmetered table scan.
    """
    caller.require("export:read")

    columns = _DATASETS.get(dataset)
    if columns is None:
        raise ProblemDetailError(
            status_code=HTTP_422_UNPROCESSABLE,
            title="Unknown dataset",
            detail=f"Available datasets are {sorted(_DATASETS)}.",
            problem_type=f"{PROBLEM_BASE}/validation-error",
        )
    try:
        chosen = export.resolve_format(fmt)
    except export.UnknownFormatError as exc:
        raise ProblemDetailError(
            status_code=HTTP_422_UNPROCESSABLE,
            title="Unknown export format",
            detail=str(exc),
            problem_type=f"{PROBLEM_BASE}/validation-error",
        ) from exc

    limit = settings.public_api.max_export_rows
    tenant_id = caller.key.tenant_id
    rows = (
        export.complaint_rows(session, tenant_id=tenant_id, since=since, until=until, limit=limit)
        if dataset == "complaints"
        else export.work_order_rows(
            session, tenant_id=tenant_id, since=since, until=until, limit=limit
        )
    )

    stamp = datetime.now(tz=UTC).date().isoformat()
    return StreamingResponse(
        export.render(rows, fmt=chosen, columns=columns),
        media_type=chosen.media_type,
        headers={
            "Content-Disposition": (
                f'attachment; filename="nemesis-{dataset}-{stamp}.{chosen.extension}"'
            ),
            # The row cap is announced rather than silently applied. An extract
            # truncated at a hundred thousand rows without saying so is a
            # dataset a researcher will publish conclusions from.
            "X-Export-Row-Limit": str(limit),
            "Cache-Control": "no-store",
        },
    )


