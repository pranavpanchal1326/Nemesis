@portal_router.get("/developers", response_class=HTMLResponse, include_in_schema=False)
async def portal(request: Request) -> Response:
    """The human-readable entry point. Generated from the same registries the API uses."""
    today = datetime.now(tz=UTC).date()
    version_rows = "".join(
        f"<tr><td><code>{html.escape(v.name)}</code></td>"
        f"<td>{html.escape(str(v.status))}</td>"
        f"<td>{v.released_on.isoformat()}</td>"
        f"<td>{'—' if v.sunset_on is None else v.sunset_on.isoformat()}</td>"
        f"<td>{html.escape(v.description)}</td></tr>"
        for v in all_versions()
    )
    scope_rows = "".join(
        f"<tr><td><code>{html.escape(name)}</code></td><td>{html.escape(why)}</td></tr>"
        for name, why in sorted(keys.SCOPES.items())
    )
    event_rows = "".join(
        f"<li><code>{html.escape(name)}</code></li>"
        for name in sorted(webhooks.known_event_types())
    )
    _ = today

    body = _PORTAL_TEMPLATE.format(
        base=html.escape(str(request.base_url).rstrip("/")),
        version_rows=version_rows,
        scope_rows=scope_rows,
        event_rows=event_rows,
        notice_days=PUBLIC_API_NOTICE_DAYS,
        tolerance=webhooks.RECOMMENDED_TOLERANCE_SECONDS,
        signature_header=html.escape(webhooks.SIGNATURE_HEADER),
        verify_source=html.escape(_VERIFY_EXAMPLE),
    )
    return HTMLResponse(content=body)


#: A worked verification example, in the reader's language rather than ours.
#:
#: Shipped because every integrator writes this function and most of them write
#: ``==`` instead of a constant-time comparison, which reintroduces the signature
#: forgery the scheme exists to prevent. ``integrations.webhooks.verify`` is the
#: same algorithm, executed by this repository's own test suite — so the example
#: on this page is one that has been run rather than one that was typed.
_VERIFY_EXAMPLE = """import hashlib, hmac, time

def verify(secret: str, body: bytes, header: str, tolerance: int = 300) -> bool:
    parts = dict(p.split("=", 1) for p in header.split(",") if "=" in p)
    issued, presented = int(parts["t"]), parts["v1"]
    if abs(int(time.time()) - issued) > tolerance:
        return False                      # replay outside the window
    expected = hmac.new(
        secret.encode(), f"{issued}.".encode() + body, hashlib.sha256
    ).hexdigest()
    return hmac.compare_digest(expected, presented)   # not ==
"""


